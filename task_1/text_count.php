<?php

// 1. Укажите переменную и передайте ей значение пути к файлу. 
$filePath = 'C:\Users\Lenovo\Desktop\src\task_1\text\pg16.txt';


function countWords($file)
{
    // 1. Открывать файл для чтения. $fp — это дескриптор файла, указатель на открытый файл
    // Режим 'r' (read)
    $fp = fopen($file, "r");

    // Проверка успешности открытия файла. Если fopen() вернёт false (файл не найден или нет прав доступа), функция возвращает false
    if (!$fp) {
    
        return false;
    }

    // 2. Считать содержимое с помощью fread().
    // fileSize() возвращает размер файла в байтах. fread() считывает весь файл в переменную $content
    $content = fread($fp, filesize($file));

    // 3. Закрыть файл для освобождения ресурсов
    fclose($fp);

    // 4. Вернуть количество слов в файле (используем str_word_count()).
    // В PHP есть специальная функция str_word_count() для подсчета слов в строке
    return str_word_count($content);
}

// 2. Если файл не найден, выведите сообщение об ошибке.
if (!file_exists($filePath)) {
    // Используем file_exists() для проверки существования файла 
    echo "Ошибка: Файл **{$filePath}** не существует или указан неверный путь." . PHP_EOL;
} else {
    // 3. Если файл существует, то вызывается функция countWords($file).
    $wordCount = countWords($filePath);

    if ($wordCount !== false) {
        // 4. Выведите результат в консоль.
        echo "Количество слов в файле [{$filePath}]: {$wordCount}" . PHP_EOL;
    } else {
        // Ошибка при открытии файла, хотя он существует (например, из-за прав доступа)
        echo "Ошибка: Не удалось открыть файл **{$filePath}** для чтения." . PHP_EOL;
    }
}



?>


